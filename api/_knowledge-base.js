/**
 * 智慧快速匹配最相關的 FAQ 條目
 */
export function matchBestFaq(queryText = '') {
  if (!queryText || typeof queryText !== 'string') return null;
  const lower = queryText.toLowerCase();

  // 優先檢測危急安全問題
  if (/漏氣|瓦斯味|臭味|嘶嘶|漏氣聲|爆炸|中毒/i.test(lower)) {
    const leakEntry = KNOWLEDGE_BASE_ENTRIES.find(e => e.isSafetyCritical);
    if (leakEntry) return leakEntry;
  }

  // 關鍵字計分匹配
  let bestMatch = null;
  let highestScore = 0;

  for (const entry of KNOWLEDGE_BASE_ENTRIES) {
    let score = 0;
    for (const kw of entry.keywords) {
      if (lower.includes(kw.toLowerCase())) {
        score += kw.length * 2; // 較長關鍵字給予更高權重
      }
    }
    if (score > highestScore) {
      highestScore = score;
      bestMatch = entry;
    }
  }

  // 門檻：至少命中 4 分才採用
  return highestScore >= 4 ? bestMatch : null;
}

